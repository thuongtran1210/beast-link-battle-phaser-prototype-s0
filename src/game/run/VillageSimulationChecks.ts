import { VillageSimulation, type VillageJob } from './VillageSimulation';
export function villageSimulationChecks(): void {
  const expect = (ok: boolean, message: string) => { if (!ok) throw Error(`Village simulation: ${message}`); };
  let completed = 0;
  const sim = new VillageSimulation(() => { completed++; });
  const job: VillageJob = { id: 'a', stationId: 'garden', kind: 'garden', home: { x: 0, y: 0 }, work: { x: 85, y: 0 }, face: 1 };
  const worker = () => sim.workers.get('a')!;
  sim.sync([job]);
  sim.step(2);
  expect(worker().phase === 'walk' && worker().x > 0 && completed === 0, 'movement precedes work and rewards');
  const before = worker();
  sim.sync([{ ...job }]);
  expect(JSON.stringify(worker()) === JSON.stringify(before), 'rebind retains phase/time/position');
  sim.step(20, true);
  expect(worker().remaining === before.remaining && worker().x === before.x, 'pause freezes progress');
  sim.step(1);
  expect(worker().phase === 'work' && completed === 0, 'arriving does not complete');
  sim.step(7.9);
  expect(completed === 0, 'incomplete work emits nothing');
  sim.step(.1);
  expect(completed === 1 && worker().phase === 'return', 'completion emits once');
  sim.step(.1);
  expect(completed === 1, 'no duplicate completion');
  const detached = worker() as { remaining: number };
  detached.remaining = 999;
  expect(worker().remaining !== 999, 'compatibility read API cannot mutate live workers');
  sim.sync([]);
  sim.step(100);
  expect(completed === 1 && sim.workers.size === 0, 'removing job cancels future work');

  const busy = new VillageSimulation(() => {});
  busy.sync([job, { ...job, id: 'b' }]);
  busy.step(4);
  expect([...busy.workers.values()].filter(w => w.phase === 'work' || w.phase === 'walk').length === 1, 'station reservation prevents competing workers');
  expect(busy.workers.get('b')?.block?.code === 'station-busy', 'reservation exposes a typed blocked reason');
  busy.sync([{ ...job, id: 'b' }]);
  busy.step(1);
  expect(busy.workers.get('b')!.phase === 'walk', 'removed owner releases reservation');
  const cancelled = new VillageSimulation(() => { completed++; });
  cancelled.sync([job]);
  cancelled.step(4);
  cancelled.sync([]);
  cancelled.step(20);
  expect(completed === 1, 'cancelled active work never completes');

  let canBegin = false;
  const blocked = new VillageSimulation(() => {}, { begin: () => canBegin ? 8 : false, advance: () => {} });
  blocked.sync([job]);
  blocked.step(3.1);
  blocked.step(.5);
  expect(blocked.workers.get('a')?.x === 85, 'blocked arrival remains at the station instead of walking backward');
  canBegin = true;
  blocked.step(1);
  expect(blocked.workers.get('a')?.phase === 'work', 'blocked arrival retries and resumes');
  sim.dispose();
  sim.sync([job]);
  sim.step(100);
  expect(sim.workers.size === 0 && completed === 1, 'disposed simulation stays inert');
}
